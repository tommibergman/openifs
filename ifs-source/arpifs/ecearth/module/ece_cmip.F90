MODULE ECE_CMIP

! =============================================================================
! *** ECE_CMIP contains everything related to CMIP6 or CMIP7:
!   - paths
!   - filenames
!   - switches
!   - namelist NAMECECMIP
! =============================================================================

    USE PARKIND1,ONLY : JPIM

    IMPLICIT NONE

    PRIVATE

    PUBLIC SETUP_ECE_CMIP

    PUBLIC LCMIP6
    PUBLIC CMIP6DATADIR
    PUBLIC LCMIP7
    PUBLIC CMIP7DATADIR
    PUBLIC SCENARIONAME
    PUBLIC NCMIPFIXYR
    PUBLIC NCMIPFIXYR_CH4
    PUBLIC LA4xCO2
    PUBLIC L1PCTCO2
    PUBLIC LGHGMONTHLY

    LOGICAL :: LCMIP6 = .FALSE.
    LOGICAL :: LCMIP7 = .FALSE.
    CHARACTER(LEN=255) :: CMIP6DATADIR = 'CMIP6DATADIR NOT SET'
    CHARACTER(LEN=255) :: CMIP7DATADIR = 'CMIP7DATADIR NOT SET'
    CHARACTER(LEN=24)  :: SCENARIONAME = 'SCENARIONAME NOT SET'
    INTEGER(KIND=JPIM) :: NCMIPFIXYR = -1
    INTEGER(KIND=JPIM) :: NCMIPFIXYR_CH4 = -1
    LOGICAL :: LA4xCO2 = .FALSE.
    LOGICAL :: L1PCTCO2 = .FALSE.
    LOGICAL :: LGHGMONTHLY = .FALSE.

    NAMELIST /NAMECECMIP/ LCMIP6
    NAMELIST /NAMECECMIP/ CMIP6DATADIR
    NAMELIST /NAMECECMIP/ LCMIP7
    NAMELIST /NAMECECMIP/ CMIP7DATADIR
    NAMELIST /NAMECECMIP/ SCENARIONAME
    NAMELIST /NAMECECMIP/ NCMIPFIXYR
    NAMELIST /NAMECECMIP/ NCMIPFIXYR_CH4
    NAMELIST /NAMECECMIP/ LA4xCO2
    NAMELIST /NAMECECMIP/ L1PCTCO2
    NAMELIST /NAMECECMIP/ LGHGMONTHLY

CONTAINS

SUBROUTINE SETUP_ECE_CMIP

    USE YOMLUN, ONLY: NULOUT, NULNAM

    ! Read EC-Earth CMIP namelist
    CALL POSNAM(NULNAM,'NAMECECMIP')
    READ(NULNAM,NAMECECMIP)

    ! Sanity checks
    IF (LCMIP6.AND.LCMIP7) &
         &   CALL ABOR1('ECE_CMIP: LCMIP6 and LCMIP7 cannot both be true.')

    ! set NCMIPFIXYR_CH4 if not already set in namelist
    IF (NCMIPFIXYR_CH4<=0) NCMIPFIXYR_CH4=NCMIPFIXYR

    IF (LA4XCO2.AND.L1PCTCO2) &
        &   CALL ABOR1('ECE_CMIP: LA4XCO2 and L1PCTCO2 cannot both be true.')

    IF ((LA4XCO2.OR.L1PCTCO2).AND.NCMIPFIXYR<=0) &
        &   CALL ABOR1('ECE_CMIP: set NCMIPFIXYR if LA4XCO2 or L1PCTCO2')

    ! print actual setting in logfile
    WRITE(NULOUT, nml=NAMECECMIP)
END SUBROUTINE SETUP_ECE_CMIP

END MODULE ECE_CMIP
